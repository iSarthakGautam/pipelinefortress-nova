import os
import sys

# redaction_eval.py
# Measures the redactor on the adversarial fixtures: recall (secrets removed) and over-redaction (benign
# snippets altered). Writes eval/redaction_results.md from the live run. No model involved.

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "ai"))
sys.path.insert(0, HERE)

from redaction.redactor import redact_finding
from redaction_fixtures import BENIGN, POSITIVES, random_secret_cases


def redact_text(text: str) -> str:
    return redact_finding({"finding_id": "x", "evidence": {"snippet_raw": text}})["snippet"]


def evaluate() -> dict:
    leaked, rows = [], []
    for name, text, secret in POSITIVES:
        out = redact_text(text)
        ok = (secret not in out) if secret else (out != text)  # secret=None: only assert something was redacted
        rows.append((name, ok))
        if not ok:
            leaked.append(name)
    over = [b for b in BENIGN if redact_text(b) != b]
    prop = [s for t, s in random_secret_cases() if s in redact_text(t)]
    return {"n_pos": len(POSITIVES), "leaked": leaked, "n_benign": len(BENIGN), "over": over,
            "n_prop": 400, "prop_leaks": len(prop)}


def main():
    r = evaluate()
    n, ok = r["n_pos"], r["n_pos"] - len(r["leaked"])
    lines = [
        "# Redaction evaluation (generated by `python3 eval/redaction_eval.py`)\n",
        "Fixtures are FAKE secrets built in `eval/redaction_fixtures.py`. The fixtures and the redactor were written by the same author "
        "(and the redactor was tuned until they passed), so recall here is an optimistic upper bound, not a guarantee. "
        "Not covered: secrets in languages/encodings not in the fixtures, secrets split across separate findings, non-Latin lookalikes beyond Cyrillic/Greek.\n",
        "| Metric | Result |", "|---|---|",
        f"| Adversarial fixtures | {n} |",
        f"| Secret removed (recall) | {ok}/{n} = {ok / n:.3f} |",
        f"| Leaked fixtures | {', '.join(r['leaked']) or 'none'} |",
        f"| Benign snippets | {r['n_benign']} |",
        f"| Over-redacted benign snippets | {len(r['over'])}/{r['n_benign']} = {len(r['over']) / r['n_benign']:.3f} |",
        f"| Over-redacted examples | {'; '.join(repr(o[:50]) for o in r['over']) or 'none'} |",
        f"| Randomised property test (known secret shapes) | {r['n_prop'] - r['prop_leaks']}/{r['n_prop']} removed |",
    ]
    out = "\n".join(lines) + "\n"
    print(out)
    with open(os.path.join(HERE, "redaction_results.md"), "w") as f:
        f.write(out)


if __name__ == "__main__":
    main()
